# 19. OAuth 2.0 学習用設定
# ==========================================

OAUTH_CLIENTS = {
    OAUTH_CLIENT_ID: {
        "secret": OAUTH_CLIENT_SECRET,
        "scopes": {
            "jobs.read",
            "jobs.write",
        },
    }
}

ISSUED_TOKENS = {}

TOKEN_LIFETIME_SECONDS = 120


# ==========================================
# 20. OAuth学習用トークン発行
# ==========================================

@app.post("/token")
def issue_token(
    grant_type: str = Form(...),
    client_id: str = Form(...),
    client_secret: str = Form(...),
    scope: str = Form("jobs.read"),
):

    if grant_type != "client_credentials":
        raise HTTPException(
            status_code=400,
            detail="unsupported_grant_type",
        )

    client = OAUTH_CLIENTS.get(client_id)

    if client is None or not secrets.compare_digest(
        client_secret,
        client["secret"],
    ):
        raise HTTPException(
            status_code=401,
            detail="invalid_client",
        )

    requested_scopes = set(scope.split())

    if not requested_scopes.issubset(
        client["scopes"]
    ):
        raise HTTPException(
            status_code=400,
            detail="invalid_scope",
        )

    access_token = secrets.token_urlsafe(32)

    ISSUED_TOKENS[access_token] = {
        "scopes": requested_scopes,
        "expires_at": (
            time.time() + TOKEN_LIFETIME_SECONDS
        ),
    }

    return {
        "access_token": access_token,
        "token_type": "Bearer",
        "expires_in": TOKEN_LIFETIME_SECONDS,
        "scope": " ".join(
            sorted(requested_scopes)
        ),
    }


# ==========================================
# 21. OAuth学習用トークン検証
# ==========================================

def verify_oauth_token(
    credentials: HTTPAuthorizationCredentials | None = Depends(
        security
    ),
):

    if credentials is None:
        raise HTTPException(
            status_code=401,
            detail="アクセストークンがありません",
            headers={"WWW-Authenticate": "Bearer"},
        )

    token_data = ISSUED_TOKENS.get(
        credentials.credentials
    )

    if token_data is None:
        raise HTTPException(
            status_code=401,
            detail="無効なアクセストークンです",
            headers={"WWW-Authenticate": "Bearer"},
        )

    if time.time() >= token_data["expires_at"]:
        raise HTTPException(
            status_code=401,
            detail="アクセストークンの有効期限が切れています",
            headers={"WWW-Authenticate": "Bearer"},
        )

    return token_data


