def insert_job(job: JobInput):

    with engine.begin() as conn:

        if IS_SQLITE:

            result = conn.execute(
                text("""
                    INSERT INTO jobs (
                        title, location, salary
                    )
                    VALUES (
                        :title, :location, :salary
                    )
                """),
                job.model_dump(),
            )

            job_id = result.lastrowid

        else:

            job_id = conn.execute(
                text("""
                    INSERT INTO jobs (
                        title, location, salary
                    )
                    VALUES (
                        :title, :location, :salary
                    )
                    RETURNING id
                """),
                job.model_dump(),
            ).scalar_one()

    return Job(
        id=job_id,
        **job.model_dump(),
    )


