API_TOKENS = {
    ADMIN_TOKEN: "admin",
}

if READ_TOKEN and READ_TOKEN != ADMIN_TOKEN:
    API_TOKENS[READ_TOKEN] = "read"

security = HTTPBearer(
    auto_error=False,
    description="学習用Bearerトークン",
)


def verify_token(
    credentials: HTTPAuthorizationCredentials | None = Depends(
        security
    ),
):

    if credentials is None:
        raise HTTPException(
            status_code=401,
            detail="アクセストークンがありません",
            headers={"WWW-Authenticate": "Bearer"},
        )

    token = credentials.credentials

    role = None

    for stored_token, stored_role in API_TOKENS.items():

        if secrets.compare_digest(
            token,
            stored_token,
        ):
            role = stored_role
            break

    if role is None:
        raise HTTPException(
            status_code=401,
            detail="無効なアクセストークンです",
            headers={"WWW-Authenticate": "Bearer"},
        )

    return role


def require_admin(
    role: str = Depends(verify_token),
):

    if role != "admin":
        raise HTTPException(
            status_code=403,
            detail="書き込み権限がありません",
        )

    return role


